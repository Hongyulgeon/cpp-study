// [문제] int 값 2개를 입력받아 합계를 출력하라
//
// [배운 점]
// - std::cin >> a >> b 처럼 >>를 이어 쓰면 여러 값을 한 번에 입력받을 수 있다
// - 숫자 자리에 글자를 입력하면 cin이 실패 상태가 되어 이후 입력이 전부 무시된다
// - 그래서 입력 성공 여부를 검사해야 무한 반복을 막을 수 있다
// - std::cin >> a 는 입력을 받고 std::cin 자신을 반환한다
//   그래서 >>를 이어 쓸 수 있고, if 조건에도 넣을 수 있다
// - 조건 안에 쓴 식도 실제로 실행된다
//   (cin을 if 밖과 안에 둘 다 써서 입력을 두 번 받는 버그를 겪음)
#include <iostream>
#include <print>

int main()
{
    while (true) {
        int a{}, b{};   // {}로 초기화하면 0이 들어감. 초기화 안 하면 쓰레기값
        std::cout << "정수 2개를 입력해주십시오." << '\n';
        if (!(std::cin >> a >> b)) break;   // 입력 실패 시 종료
        std::println("정수의 합: {} + {} = {}", a, b, a + b);
    }
}